/**
 * ACI 索引转 0xRRGGBB。
 * 索引 7 在深色画布上显示为白色；索引 0 / 256 表示 ByBlock / ByLayer，
 * 由调用方先解析到具体颜色，这里只处理 1..255 的有效索引。
 */
export function aciToRgb(index: number): number {
  if (!Number.isInteger(index) || index < 1 || index > 255) return CAD_WHITE
  if (index === 7) return CAD_WHITE
  return ACI_TABLE[index]
}

/** 图纸未给出有效 ACI 时使用的确定性调色板（保证同一图层每次颜色一致） */
const LAYER_PALETTE: readonly number[] = [
  0x6ea8fe, 0x7dd3a7, 0xf6c177, 0xe58fb4, 0x9d8df1,
  0x67c7d6, 0xf29e6b, 0xa7c957, 0xc0a2ff, 0x8fb8de,
  0xe3b341, 0x76b7b2,
]

/**
 * 根据图层名派生确定性颜色。
 * 使用 FNV-1a 哈希，保证同名图层颜色稳定，且不需要 Math.random。
 */
export function layerColorFromName(name: string): number {
  let hash = 0x811c9dc5
  for (let i = 0; i < name.length; i += 1) {
    hash ^= name.charCodeAt(i)
    hash = Math.imul(hash, 0x01000193) >>> 0
  }
  return LAYER_PALETTE[hash % LAYER_PALETTE.length]
}

/** 0xRRGGBB 转 CSS 颜色字符串，供图层面板色块使用 */
export function rgbToCss(color: number): string {
  const r = (color >> 16) & 0xff
  const g = (color >> 8) & 0xff
  const b = color & 0xff
  return `rgb(${r}, ${g}, ${b})`
}
